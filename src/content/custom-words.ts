// ── Готовые карточки для слов вне банка (0.61.0) ────────────────────────────
//
// Зачем этот файл.
//
// Своё слово из школьного списка раньше получало карточку «из воздуха»:
// подсказка «Слово из списка к контрольной», предложение «Контрольная: ____.»
// и картинка-заглушка с книгой. Ребёнок видел задание, по которому нельзя
// понять, о каком слове речь, — и это не помогало, а мешало.
//
// Здесь для слов, которые встречаются в школьных списках, лежит всё нужное:
//   • image    — картинка в `public/words/` (та же серия, что у 257 слов банка);
//   • hint     — объяснение значения, по которому слово можно узнать;
//   • sentence — предложение с пропуском ____ (контекст, а не «Контрольная»);
//   • mnemonic — подсказка-запоминалка (у грамматических терминов — правило).
//
// Карточка собирается в `makeCustomWord`: если слово есть в этом реестре,
// берутся его поля; иначе — автополя (слоги, ударение, «опасные» буквы)
// и честная пометка «проверьте ударение».
//
// Как пополнять: новое слово из школьного списка → строка здесь + картинка
// в `public/words/` + (если нужно) ударение в `stress-dict.ts`.
// Проверки: `tests/lists-ui.test.tsx` требует у каждого слова пресета
// картинку и осмысленную подсказку.

export interface CustomWordCard {
  /** Имя файла в public/words без расширения. */
  image: string;
  /** Что это за слово — по этой фразе ребёнок должен узнать значение. */
  hint: string;
  /** Предложение с пропуском ____. */
  sentence: string;
  /** Мнемоника или правило: как запомнить написание/смысл. */
  mnemonic?: string;
  /** Слоги, если стандартное деление по гласным не подходит. */
  syllables?: string[];
}

/**
 * Ключ — слово в нижнем регистре и с «е» вместо «ё» (та же нормализация,
 * что в `matchKey` из `engine/word-lists.ts`).
 */
export const CUSTOM_WORD_CARDS: Record<string, CustomWordCard> = {
  // «Прощайте» — форма вежливости, которой нет в банке (там есть «прощай»).
  прощайте: {
    image: 'proshchayte',
    hint: 'вежливое слово, когда прощаешься надолго или со многими',
    sentence: 'Уходя из класса, ребята сказали: «____!»',
    mnemonic: 'прощАйте — как «прощАй», только к нескольким людям или вежливо',
  },
  // Части речи из программы 4 класса: значение объясняется через роль в предложении.
  подлежащее: {
    image: 'podlezhashchee',
    hint: 'главный член предложения: о ком или о чём говорится',
    sentence: 'В предложении «Дети играют» ____ — это слово «дети».',
    mnemonic: 'подлЕжащее — «лежит в основе» предложения, от слова «подлежать»',
  },
  сказуемое: {
    image: 'skazuemoe',
    hint: 'член предложения: что говорится о подлежащем, что оно делает',
    sentence: 'В предложении «Дети играют» ____ — это слово «играют».',
    mnemonic: 'сказУемое — от «сказать»: что про подлежащее скАзано',
  },
};

/** Есть ли готовая карточка для слова (ключ — как в `matchKey`). */
export function customWordCard(key: string): CustomWordCard | undefined {
  return CUSTOM_WORD_CARDS[key];
}
