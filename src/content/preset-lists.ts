// ── Готовые списки слов к контрольной (0.59.0) ──────────────────────────────
//
// Зачем: вставлять 26 слов руками — лишняя работа. Список, который прислали
// из школы, живёт здесь как готовый пресет: в «Родителям → 🏫 Списки» его
// добавляют **одной кнопкой**, без копирования текста.
//
// Формат нарочно тот же, что у вставки из чата: `words` — строки как их
// прислали. Разбор (`parseWordList`) сам находит слова в банке 257 карточек
// и создаёт карточки для тех, которых там нет («подлежащее», «сказуемое»,
// «прощайте»), поэтому пресет не дублирует логику и не может «разъехаться»
// с обычным списком.
//
// Новый школьный список = новый элемент массива + версия (docs/RELEASE).
// Пресеты общие для всех профилей: список копируется в профиль при нажатии,
// дальше живёт своей жизнью (его можно переименовать или удалить).

export interface PresetList {
  /** Стабильный id: по нему тест и журнал понимают, какой пресет добавили. */
  id: string;
  /** Название списка, которое увидит ребёнок. */
  title: string;
  /** Слова как их прислали из школы: по одному в строке. */
  words: string[];
  /** Откуда список: показывается родителю мелким текстом. */
  source: string;
}

