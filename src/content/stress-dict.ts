// ── Словарь ударений для слов вне банка (0.59.1) ────────────────────────────
//
// Зачем: автополе «ударение на последнюю гласную» подходит для большинства
// коротких слов, но ломается на школьных терминах и вежливых формах:
//
//   подлежащее → ставилось «подлежащЕе», правильно «подлЕжащее»
//   сказуемое  → ставилось «сказуемоЕ»,  правильно «сказУемое»
//   прощайте   → ставилось «прощайтЕ»,   правильно «прощАйте»
//
// Правило проекта: не угадывать там, где ответ известен. Поэтому слова,
// которые встречаются в школьных списках, приходят с готовым ударением,
// а автополе остаётся только для слов, которых тут нет.
//
// Формат: ключ — слово в нижнем регистре и с «е» вместо «ё» (та же
// нормализация, что в `matchKey`), значение — индекс УДАРНОЙ БУКВЫ в слове
// (как в `Word.stress`: индекс символа, не номер гласной).
//
// Важно: родитель всегда может поставить ударение сам — тогда флаг
// `stressManual` в карточке сохраняет его выбор и словарь его не перебивает.

/** Известные ударения: слово → индекс ударной буквы. */
export const KNOWN_STRESS: Record<string, number> = {
  // части речи из программы 4 класса
  подлежащее: 4, // подлЕжащее
  сказуемое: 4, // сказУемое
  // вежливые формы
  прощайте: 4, // прощАйте
};

/** Есть ли готовое ударение для слова (ключ — как в `matchKey`). */
export function knownStress(key: string): number | undefined {
  return KNOWN_STRESS[key];
}
