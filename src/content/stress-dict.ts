// ── Словарь ударений для слов вне банка (0.59.1, расширен в 0.60.0) ────────
//
// Зачем: свои слова из школьного списка приходят без разметки, и ударение
// ставит автополе. Правило «последняя гласная» верно для большинства коротких
// слов, но ломается на терминах и формах:
//
//   подлежащее → «подлежащЕе» вместо «подлежАщее»  (ударение на «а», 3-й слог)
//   сказуемое  → «сказуемоЕ»  вместо «сказУемое»
//   прощайте   → «прощайтЕ»   вместо «прощАйте»
//
// ВАЖНО (исправлено в 0.61.1): в первой версии этого словаря у «подлежащее»
// стояло ударение на «е» (подлЕжащее) — это была ошибка. Проверено по
// словарям: Викисловарь — «под-ле-жа́-ще·е», Грамота.ру и Малый академический
// словарь — «ПОДЛЕЖА́ЩЕЕ». Ударная буква — «а» (индекс 6).
//
// Поэтому слова, которые встречаются в школьных списках, приходят с готовым
// ударением, а автополе остаётся только для слов, которых здесь нет — и в
// предпросмотре списка такие слова честно помечаются «проверьте ударение».
//
// Формат: ключ — слово в нижнем регистре и с «е» вместо «ё» (та же
// нормализация, что в `matchKey`), значение — индекс УДАРНОЙ БУКВЫ в слове
// (как в `Word.stress`: индекс символа, а не номер гласной). В комментарии —
// то же слово с заглавной ударной буквой, чтобы файл читался глазами.
//
// Важно: ручной выбор родителя (`stressManual`) словарь не перебивает.

