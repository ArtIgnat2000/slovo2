/**
 * Экскурсии внутри научных баз (0.76.0).
 *
 * Просьба ребёнка: «на базу хочется зайти внутрь, а не только смотреть снаружи».
 * У каждой базы — пять комнат. Картинки появляются по тапу и закольцованы,
 * а к каждой комнате приложены два «крючка»:
 *
 * - `fact` — короткий настоящий факт (атом даёт пар, микросхема похожа на город,
 *   на Луне тяжесть в шесть раз меньше): ребёнок листает картинки и незаметно
 *   узнаёт новое;
 * - `find` — задание «найди на картинке»: без него интерьер просто красивый,
 *   а с ним ребёнок разглядывает детали и возвращается к картинке ещё раз.
 *
 * Данные лежат без React, как остальные каталоги (`engine/buildings.ts`),
 * чтобы тест мог сверить их целиком: у каждой базы ровно пять комнат, у каждой
 * комнаты есть файл `public/base-tours/<baseId>-<номер>.webp`.
 *
 * Картинки — фотореалистичные визуализации (не документальные снимки): они
 * живут вне precache PWA (`vite.config.ts`, кэш `slovo2-base-tours`), потому
 * что 25 интерьеров крупнее всего остального офлайн-набора, а нужны только
 * тому, кто открыл комнату.
 */

export interface BaseTourStop {
  /** Короткий id комнаты — для ключей React и проверок. */
  id: string;
  /** Название комнаты: «Реакторный зал». */
  title: string;
  /** Эмодзи-подсказка, с какой стороны смотреть. */
  emoji: string;
  /** Познавательный факт — одна фраза, понятная младшему школьнику. */
  fact: string;
  /** Задание-поиск: что найти на картинке. */
  find: string;
}

export interface BaseTour {
  baseId: string;
  /** Сколько всего комнат внутри — по числу интерьеров. */
  stops: BaseTourStop[];
}

