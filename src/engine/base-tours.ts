export const BASE_TOUR_BY_ID: Record<string, BaseTour> = Object.fromEntries(
  BASE_TOURS.map((tour) => [tour.baseId, tour]),
);

/** Комнаты базы; пустой список — база без экскурсии (данные ещё не готовы). */
export function baseTourStops(baseId: string): BaseTourStop[] {
  return BASE_TOUR_BY_ID[baseId]?.stops ?? [];
}

/** Сколько всего кадров в кольце: фасад + комнаты. */
export function baseTourFrames(baseId: string): number {
  return 1 + baseTourStops(baseId).length;
}

/** Файл интерьера: public/base-tours/<baseId>-<номер>.webp, номер с единицы. */
export function baseTourImageUrl(baseId: string, index: number): string {
  return `${import.meta.env.BASE_URL}base-tours/${baseId}-${index + 1}.webp`;
}
