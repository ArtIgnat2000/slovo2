
/**
 * Ё стоит в начале третьей строки — как на стандартной мобильной русской
 * раскладке (iOS/Gboard). С 0.64.0 «е» вместо «ё» при наборе засчитывается
 * (sameTypedWord): дети часто не находят эту клавишу. Но сама клавиша
 * остаётся — в заданиях с выбором буквы ё по-прежнему нужна.
 */
export const KEYBOARD_ROWS = [
  ['й', 'ц', 'у', 'к', 'е', 'н', 'г', 'ш', 'щ', 'з', 'х'],
  ['ф', 'ы', 'в', 'а', 'п', 'р', 'о', 'л', 'д', 'ж', 'э'],
  ['ё', 'я', 'ч', 'с', 'м', 'и', 'т', 'ь', 'б', 'ю', '⌫'],
];

/**
 * Своя раскладка: системная клавиатура на телефоне перекрывает задание,
 * а ребёнку важно видеть слово и предложение одновременно с набором.
 */
export function Keyboard({ onKey, disabled }: { onKey: (k: string) => void; disabled?: boolean }) {
  return (
    <div className="keyboard">
      {KEYBOARD_ROWS.map((row, i) => (
        <div className="kb-row" key={i}>
          {row.map((k) => (
            <button
              key={k}
              className={`key ${k === '⌫' ? 'back' : ''}`}
              disabled={disabled}
              onClick={() => onKey(k)}
            >
              {k}
            </button>
          ))}
        </div>
      ))}
    </div>
  );
}
