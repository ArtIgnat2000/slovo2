/** Есть ли для вещи цветной карандашный рисунок. */
export function hasCarArt(id: string): boolean {
  return id in CAR_ART;
}

/** Подпись характера машины под рисунком. */
export function carKind(id: string): string | null {
  return CAR_ART[id]?.kind ?? null;
}

/** Чем машина узнаётся — для подробной карточки. */
export function carNote(id: string): string | null {
  return CAR_ART[id]?.note ?? null;
}

/**
 * Alt для рисунка: имя вещи + характер, без марки.
 * `fallback` — на случай, если рисунка нет (тогда остаётся название товара).
 */
export function carAlt(id: string, fallback = ''): string {
  const art = CAR_ART[id];
  if (!art) return fallback;
  return `${fallback || art.kind} — ${art.kind.toLowerCase()}`;
}

/** URL рисунка: public/cars/<id>.webp с учётом базы сборки. */
export function carArtUrl(id: string): string | null {
  if (!hasCarArt(id)) return null;
  return `${import.meta.env.BASE_URL}cars/${id}.webp`;
}

/**
 * Рисунок машины.
 *
 * `tint` — цвет «цветного карандаша» поверх готового рисунка (тюнинг). Он
 * накладывается режимом `color` и маскируется альфой самого рисунка: бумага
 * вокруг машины остаётся прозрачной, а штриховка, блики и светотень никуда
 * не деваются. Без tint — рисунок в своих природных цветах.
 *
 * Размер задаёт контекст (CSS): карточка витрины, полка техники, гардероб,
 * крупный лист в подробной карточке. Так один компонент обслуживает все места,
 * где раньше стоял SVG.
 */
export function CarArt({
  id,
  tint,
  alt,
  className,
}: {
  id: string;
  /** Цветной карандаш поверх рисунка; null/undefined — природные цвета. */
  tint?: string | null;
  /** Пустая строка — рисунок декоративный (карточка уже озвучена). */
  alt?: string;
  className?: string;
}) {
  const src = carArtUrl(id);
  if (!src) return null;
  const style = tint
    ? ({
        '--car-tint': tint,
        '--car-mask': `url("${src}")`,
      } as unknown as CSSProperties)
    : undefined;
  return (
    <span className={`car-art${className ? ` ${className}` : ''}`} style={style}>
      <img src={src} width={720} height={480} alt={alt ?? ''} draggable={false} decoding="async" loading="lazy" />
      {tint && <span className="car-art-wash" aria-hidden="true" />}
    </span>
  );
}
