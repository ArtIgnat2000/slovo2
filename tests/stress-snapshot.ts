// читался глазами. `tests/stress.test.ts` (входит в `npm run test:content`)
// сверяет контент со снимком и падает при любом расхождении: и на сдвинутом
// ударении, и на переименованном слове, и на новом слове без записи.
//
// Как менять осознанно: если ударение в контенте действительно правится
// (нашлась ошибка) — поправьте число здесь ТОЙ ЖЕ правкой, тогда диф покажет
// ровно изменённые слова.
//
// Формат: ключ — слово как в контенте, значение — индекс ударной БУКВЫ.

